export function tiIcon(name?: string | null): string {
  const raw = String(name || '').trim().replace(/^(bi|ti)\s+/, '');
  if (raw.startsWith('ti-')) return `ti ${raw}`;
  if (raw.startsWith('bi-')) return `ti ti-${BI_TO_TI[raw.slice(3)] || 'point'}`;
  if (raw.startsWith('iconoir-') || raw.startsWith('ph')) return raw;
  return 'ti ti-point';
}
